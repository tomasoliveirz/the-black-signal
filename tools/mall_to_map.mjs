// Turns shared/maps/mall.json (exported set: collision boxes + walking route) into the map module the game loads.
// usage: node tools/mall_to_map.mjs
import fs from 'node:fs';
const d = JSON.parse(fs.readFileSync('shared/maps/mall.json', 'utf8'));
const cx = (d.bounds.minX + d.bounds.maxX) / 2, cz = (d.bounds.minZ + d.bounds.maxZ) / 2, r = (v) => Math.round(v * 100) / 100;
const pt = (p) => ({ x: r(p.x - cx), z: r(p.z - cz) });
const data = {
  model: './assets/maps/mall.glb', offset: { x: r(-cx), y: r(-d.floorY), z: r(-cz) },
  bounds: { minX: r(d.bounds.minX - cx), maxX: r(d.bounds.maxX - cx), minZ: r(d.bounds.minZ - cz), maxZ: r(d.bounds.maxZ - cz) },
  boxes: d.boxes.map((b) => ({ ...pt(b), w: r(b.w), d: r(b.d), h: r(b.h) })),
  spawn: pt(d.spawn), goal: pt(d.goal), route: d.route.map(pt), open: d.open.map(pt),
};
const theme = { minNight: 0.38, fog: [8, 58], tuft: 0, litter: 0, mountains: false, fogDay: '#8f8894', fogNight: '#0b0b10', zenith: '#4c4a58', grass: '#8a867e', path: '#9c968c' };
fs.writeFileSync('shared/maps/mall.js', `// generated by tools/mall_to_map.mjs from the Marrow Mall set (tomy_studios)\nimport { registerMesh } from '../layout.js';\nregisterMesh('mall', ${JSON.stringify({ name: 'Marrow Mall', sub: 'Shopping abandonado', theme, data })});\n`);
fs.writeFileSync('shared/maps/index.js', "// Imported sets register themselves here.\nimport './mall.js';\n");
console.log('mall:', data.boxes.length, 'caixas,', data.open.length, 'pontos livres, rota de', data.route.length, 'pontos, limites', JSON.stringify(data.bounds));
