const englishByPortuguese = new Map(Object.entries(portuguese).map(([en, pt]) => [pt, en]));
let language = 'en';
try { if (localStorage.getItem('bs.language') === 'pt-PT') language = 'pt-PT'; } catch {}
export const getLanguage = () => language;
export function t(key, values = {}) {
  const text = language === 'pt-PT' ? portuguese[key] ?? key : key;
  return text.replace(/\{(\w+)\}/g, (match, key) => String(values[key] ?? match));
}
export function translateText(value) {
  return t(englishByPortuguese.get(value) ?? value);
}
function render() {
  document.documentElement.lang = language;
  for (const node of document.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const attribute of ['placeholder', 'title', 'aria-label']) {
    for (const node of document.querySelectorAll(`[data-i18n-${attribute}]`)) {
      node.setAttribute(attribute, t(node.getAttribute(`data-i18n-${attribute}`)));
    }
  }
  for (const id of ['language', 'guide-language']) {
    const select = document.getElementById(id);
    if (select) select.value = language;
  }
}
export function setLanguage(value) {
  if (!['en', 'pt-PT'].includes(value)) return;
  language = value;
  try { localStorage.setItem('bs.language', language); } catch {}
  render();
  window.dispatchEvent(new CustomEvent('language-change', { detail: { language } }));
}
render();
document.getElementById('language')?.addEventListener('change', event => setLanguage(event.target.value));
